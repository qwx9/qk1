/* The following C code will generate a colormap.lmp that is nearly (but not exactly) identical to
 * the Quake colormap. Slightly modified code originally written by metlslime who placed it in the
 * public domain. */

static byte
rgb2pal(const byte *pal, const int *rgb)
{
	int i, j, dist, best, ind;

	ind = 0;
	best = Q_MAXINT;
	for(i = 0; i < 256; i++) {
		dist = 0;
		for(j = 0; j < 3; j++) {
			// note that we could use RGB luminosity bias for greater accuracy,
			// but quake's colormap apparently didn't do this
			int d = abs(rgb[j] - pal[i * 3 + j]);
			dist += d * d;
		}
		if(dist < best) {
			ind = i;
			best = dist;
		}
	}
	return ind;
}

const byte *
q1_build_colormap(const byte *pal)
{
	int i, x, y, n, rgb[3];
	byte *cm;

	cm = Hunk_Alloc(16384);
	for(x = 0; x < 256; x++) {
		for(y = 0; y < 64; y++) {
			n = y * 256 + x;
			if(x >= 256 - 32)
				cm[n] = x; // fullbright
			else {
				for(i = 0; i < 3; i++) {
					rgb[i] = (pal[x * 3 + i] * (63 - y) + 16) / 32;
					if(rgb[i] > 0xff)
						rgb[i] = 0xff;
				}
				cm[n] = rgb2pal(pal, rgb);
			}
		}
	}
	return cm;
}
